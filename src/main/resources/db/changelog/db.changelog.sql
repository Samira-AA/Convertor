-- Cola durable independiente del historial antiguo. Cada POST crea un trabajo nuevo.
CREATE TABLE pdfa_trabajo (
    id UUID PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES pdfa_cliente(id),
    perfil VARCHAR(2) NOT NULL CHECK (perfil IN ('1b', '2b')),
    estado VARCHAR(16) NOT NULL CHECK (estado IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED', 'EXPIRED')),
    cuota_reservada BOOLEAN NOT NULL DEFAULT FALSE,
    token_ejecucion UUID,
    intentos integer NOT NULL DEFAULT 0,
    lease_hasta TIMESTAMP WITH TIME ZONE,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_finalizacion TIMESTAMP WITH TIME ZONE,
    fecha_expiracion TIMESTAMP WITH TIME ZONE,
    bytes_salida BIGINT NOT NULL DEFAULT 0,
    error VARCHAR(500)
);
CREATE INDEX ix_pdfa_trabajo_pendientes ON pdfa_trabajo (estado, fecha_creacion);
CREATE INDEX ix_pdfa_trabajo_cliente ON pdfa_trabajo (id_cliente, fecha_creacion);
CREATE INDEX ix_pdfa_trabajo_lease ON pdfa_trabajo (lease_hasta) WHERE estado = 'RUNNING';
