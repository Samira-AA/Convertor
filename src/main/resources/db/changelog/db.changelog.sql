--changeset sumax:002-conversion-integrity dbms:mysql splitStatements:false logicalFilePath:db/changelog/002-conversion-integrity.sql
-- La identidad y el resultado final de un trabajo no pueden reutilizarse para otro cobro.
-- La cuota se reserva y devuelve en la transacción de la API; este trigger no vuelve a descontarla.
CREATE TRIGGER trg_pdfa_conversion_identity
BEFORE UPDATE ON pdfa_conversion
FOR EACH ROW
BEGIN
    IF NOT (OLD.client_id <=> NEW.client_id)
        OR NOT (OLD.idempotency_key_hash <=> NEW.idempotency_key_hash)
        OR NOT (OLD.request_hash <=> NEW.request_hash)
        OR NOT (OLD.profile <=> NEW.profile)
        OR NOT (OLD.id <=> NEW.id) THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'La identidad de una conversion es inmutable';
    END IF;
    IF OLD.status <> 'IN_PROGRESS' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Una conversion finalizada no puede volver a procesarse ni cobrarse';
    END IF;
END;
--rollback DROP TRIGGER trg_pdfa_conversion_identity;

