--changeset sumax:004-postgresql-conversion-integrity dbms:postgresql splitStatements:false logicalFilePath:db/changelog/004-postgresql-conversion-integrity.sql
-- La API reserva/devuelve la cuota en una transacción. El trigger protege la identidad
-- y el estado final de la conversión sin descontar nuevamente la cuota.
CREATE FUNCTION enforce_pdfa_conversion_identity() RETURNS TRIGGER
LANGUAGE plpgsql AS $body$
BEGIN
    IF OLD.client_id IS DISTINCT FROM NEW.client_id
        OR OLD.idempotency_key_hash IS DISTINCT FROM NEW.idempotency_key_hash
        OR OLD.request_hash IS DISTINCT FROM NEW.request_hash
        OR OLD.profile IS DISTINCT FROM NEW.profile
        OR OLD.id IS DISTINCT FROM NEW.id THEN
        RAISE EXCEPTION USING ERRCODE = '45000',
            MESSAGE = 'La identidad de una conversion es inmutable';
    END IF;
    IF OLD.status <> 'IN_PROGRESS' THEN
        RAISE EXCEPTION USING ERRCODE = '45000',
            MESSAGE = 'Una conversion finalizada no puede volver a procesarse ni cobrarse';
    END IF;
    RETURN NEW;
END;
$body$;

CREATE TRIGGER trg_pdfa_conversion_identity
BEFORE UPDATE ON pdfa_conversion
FOR EACH ROW EXECUTE FUNCTION enforce_pdfa_conversion_identity();

